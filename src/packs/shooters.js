function shmup(id, name, emoji, desc, cfg) {
  return {
    id,
    name,
    emoji,
    tag: "Shooter",
    desc,
    bestMode: "max",
    mount(ctx) {
      return createShmup(ctx, { title: `${emoji} ${name}`, subtitle: cfg.hint || "Geser / panah untuk gerak · auto-tembak", ...cfg });
    },
  };
}

